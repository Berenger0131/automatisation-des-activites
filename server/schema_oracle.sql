-- ----------------------------------------------------------------------------
-- 1. Table DERS (Directions/Agences Régionales de la SONABEL)
-- ----------------------------------------------------------------------------
CREATE TABLE DERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(30) NOT NULL UNIQUE,
    NOM VARCHAR2(100) NOT NULL,
    CHEF_LIEU VARCHAR2(100) NOT NULL,
    PROVINCES VARCHAR2(400) NOT NULL,
    RESPONSABLE_NOM VARCHAR2(100),
    RESPONSABLE_EMAIL VARCHAR2(100),
    RESPONSABLE_TELEPHONE VARCHAR2(30),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ----------------------------------------------------------------------------
-- 2. Table USERS (Agents, Superviseurs, Administrateurs)
-- ----------------------------------------------------------------------------
CREATE TABLE USERS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NOM VARCHAR2(100) NOT NULL,
    PRENOM VARCHAR2(100) NOT NULL,
    TELEPHONE VARCHAR2(30) NOT NULL UNIQUE,
    EMAIL VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    PROVINCE VARCHAR2(100) NOT NULL,
    DER_ID NUMBER NOT NULL,
    ROLE VARCHAR2(30) DEFAULT 'UTILISATEUR' CHECK (ROLE IN ('UTILISATEUR', 'ADMINISTRATEUR')),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_USERS_DER FOREIGN KEY (DER_ID) REFERENCES DERS(ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 3. Table REPORTS (Rapports Hebdomadaires)
-- ----------------------------------------------------------------------------
CREATE TABLE REPORTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    DER_ID NUMBER NOT NULL,
    SEMAINE_CODE VARCHAR2(20) NOT NULL, -- Ex: "2026-W35"
    DATE_DEBUT DATE NOT NULL,
    DATE_FIN DATE NOT NULL,
    RENCONTRES_TEXTE CLOB,
    FACTURATION_MOIS VARCHAR2(50),
    FACTURATION_NB NUMBER DEFAULT 0,
    INT_CONFIG_PC NUMBER DEFAULT 0,
    INT_DEP_PC NUMBER DEFAULT 0,
    INT_CONFIG_IMP NUMBER DEFAULT 0,
    INT_DEP_IMP NUMBER DEFAULT 0,
    INT_DEP_RESEAU NUMBER DEFAULT 0,
    INT_CONFIG_LOG NUMBER DEFAULT 0,
    DIVERS_TEXTE CLOB,
    NB_SITES NUMBER DEFAULT 0,
    MAINTENANCE_PROGRAMMEE NUMBER DEFAULT 0,
    MAINTENANCE_EFFECTUEE NUMBER DEFAULT 0,
    MAINTENANCE_OBS CLOB,
    STATUT VARCHAR2(30) DEFAULT 'A_JOUR' CHECK (STATUT IN ('A_JOUR', 'EN_RETARD', 'NON_SOUMIS')),
    SOUMIS_LE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_REPORTS_USER FOREIGN KEY (USER_ID) REFERENCES USERS(ID) ON DELETE CASCADE,
    CONSTRAINT FK_REPORTS_DER FOREIGN KEY (DER_ID) REFERENCES DERS(ID) ON DELETE CASCADE
);

-- ----------------------------------------------------------------------------
-- 4. Table MISSIONS (Missions de Terrain rattachées à un rapport)
-- ----------------------------------------------------------------------------
CREATE TABLE MISSIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPORT_ID NUMBER NOT NULL,
    LIEU VARCHAR2(150) NOT NULL,
    DATE_DEBUT DATE NOT NULL,
    DATE_FIN DATE NOT NULL,
    OBJET VARCHAR2(300) NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT FK_MISSIONS_REPORT FOREIGN KEY (REPORT_ID) REFERENCES REPORTS(ID) ON DELETE CASCADE
);

